"""Human-readable HTML rendering of skill results.

HTML is generated from the *same* Markdown each skill already produces, not
from a second set of templates. Two independent renderers would drift, and a
number appearing differently in the HTML than in the Markdown is exactly the
kind of discrepancy this project exists to avoid.

The converter handles only the closed set of Markdown constructs these skills
emit -- headings, bullets (one nesting level), pipe tables, bold, inline code,
paragraphs. It is not a general Markdown implementation and does not need to
be: the input is machine-generated by code in this package.

No external dependencies, no network, no remote assets. The output is a
single self-contained file.
"""

from __future__ import annotations

import re
from html import escape

_BOLD = re.compile(r"\*\*(.+?)\*\*")
_CODE = re.compile(r"`([^`]+)`")

STATUS_LABEL = {"ok": "完成", "degraded": "部分降級", "unavailable": "不可得"}


def _inline(text: str) -> str:
    """Escape, then apply inline formatting.

    Escaping first is deliberate: any ``<`` in the source becomes ``&lt;``
    before the formatting patterns run, so content can never introduce markup.
    ``**`` and backticks are untouched by escaping, so the patterns still match.
    """
    out = escape(text, quote=False)
    out = _BOLD.sub(r"<strong>\1</strong>", out)
    return _CODE.sub(r"<code>\1</code>", out)


def _render_table(rows: list[str]) -> str:
    """Render a pipe table, skipping the ``|---|`` separator row."""
    parsed = [[cell.strip() for cell in row.strip().strip("|").split("|")] for row in rows]
    body = [r for r in parsed[1:] if not all(set(c) <= set("-: ") for c in r)]

    head_html = "".join(f"<th>{_inline(c)}</th>" for c in parsed[0])
    body_html = "".join(
        "<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in row) + "</tr>" for row in body
    )
    return (
        '<div class="scroll"><table><thead><tr>'
        f"{head_html}</tr></thead><tbody>{body_html}</tbody></table></div>"
    )


def markdown_subset_to_html(markdown: str) -> str:
    """Convert the Markdown this package emits into an HTML fragment.

    Supports: ``#``/``##``/``###`` headings, ``-`` bullets with one level of
    two-space nesting, pipe tables, ``**bold**``, ``` `code` ```, and blank-line
    separated paragraphs. A paragraph that is entirely bold is treated as a
    sub-heading, which is how the limitations block is marked up.
    """
    html: list[str] = []
    bullets: list[tuple[int, str]] = []
    table: list[str] = []
    paragraph: list[str] = []

    def flush_bullets() -> None:
        if not bullets:
            return
        html.append("<ul>")
        depth = 0
        for level, text in bullets:
            while level > depth:
                html.append("<ul>")
                depth += 1
            while level < depth:
                html.append("</ul>")
                depth -= 1
            html.append(f"<li>{_inline(text)}</li>")
        while depth > 0:
            html.append("</ul>")
            depth -= 1
        html.append("</ul>")
        bullets.clear()

    def flush_table() -> None:
        if table:
            html.append(_render_table(table))
            table.clear()

    def flush_paragraph() -> None:
        if not paragraph:
            return
        joined = " ".join(paragraph)
        stripped = joined.strip()
        if stripped.startswith("**") and stripped.endswith("**") and stripped.count("**") == 2:
            html.append(f'<h4 class="lim">{_inline(stripped[2:-2])}</h4>')
        else:
            html.append(f"<p>{_inline(joined)}</p>")
        paragraph.clear()

    def flush_all() -> None:
        flush_bullets()
        flush_table()
        flush_paragraph()

    for raw in markdown.splitlines():
        line = raw.rstrip()
        stripped = line.strip()

        if not stripped:
            flush_all()
            continue

        if stripped.startswith("|"):
            flush_bullets()
            flush_paragraph()
            table.append(stripped)
            continue
        flush_table()

        for hashes, tag in (("### ", "h3"), ("## ", "h2"), ("# ", "h1")):
            if stripped.startswith(hashes):
                flush_all()
                html.append(f"<{tag}>{_inline(stripped[len(hashes):])}</{tag}>")
                break
        else:
            indent = len(line) - len(line.lstrip(" "))
            if stripped.startswith("- "):
                flush_paragraph()
                bullets.append((1 if indent >= 2 else 0, stripped[2:]))
            else:
                flush_bullets()
                paragraph.append(stripped)

    flush_all()
    return "\n".join(html)


