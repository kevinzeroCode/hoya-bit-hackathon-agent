def _document(title: str, body: str) -> str:
    return (
        "<!doctype html>\n"
        '<html lang="zh-Hant">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{escape(title)}</title>\n<style>{STYLESHEET}</style>\n"
        f'</head>\n<body>\n<div class="wrap">\n{body}\n</div>\n</body>\n</html>\n'
    )


def render_section_html(result) -> str:
    """One skill's section as a standalone HTML fragment, with a status badge."""
    status = result.status
    label = STATUS_LABEL.get(status, status)
    inner = markdown_subset_to_html(result.section_markdown)
    badge = f'<span class="badge {escape(status)}">{escape(label)}</span>'

    # Attach the badge to the section heading the converter produced.
    if "</h3>" in inner:
        inner = inner.replace("</h3>", f"{badge}</h3>", 1)
    else:
        inner = badge + inner

    return f'<section class="section is-{escape(status)}">\n{inner}\n</section>'


def render_report_html(bundle, results) -> str:
    """A complete, self-contained HTML document for one asset."""
    as_of = bundle.as_of.isoformat() if bundle.as_of else "不可得"
    years = bundle.bars / 365

    coverage_rows = "".join(
        f"<tr><td><code>{escape(r.skill_id)}</code></td><td>{escape(r.skill_name)}</td>"
        f'<td><span class="badge {escape(r.status)}">'
        f"{escape(STATUS_LABEL.get(r.status, r.status))}</span></td></tr>"
        for r in results
    )

    limitations: list[str] = []
    for result in results:
        for item in result.limitations:
            entry = f"（{result.skill_id}）{item}"
            if entry not in limitations:
                limitations.append(entry)
    limitation_items = "".join(f"<li>{_inline(item)}</li>" for item in limitations)

    sections = "\n".join(render_section_html(r) for r in results)

    body = (
        f"<h1>{escape(bundle.asset)} 價格資料分析</h1>\n"
        f'<p class="meta">分析基準日（as_of）：<code>{escape(as_of)}</code></p>\n'
        f'<p class="meta">可用 K 線：{bundle.bars} 根（約 {years:.1f} 年）</p>\n'
        f'<p class="meta">資料來源類型：<code>public_market_data</code></p>\n'
        "<h2>產出覆蓋狀態</h2>\n"
        '<div class="scroll"><table><thead><tr><th>產出</th><th>名稱</th><th>狀態</th></tr>'
        f"</thead><tbody>{coverage_rows}</tbody></table></div>\n"
        "<h2>分析產出</h2>\n"
        f"{sections}\n"
        f'<div class="limitations"><h2>總體限制與揭露</h2><ul>{limitation_items}</ul></div>\n'
        "<footer><p>本文所有數值由決定性計算產生，未經模型生成或調整；"
        "相同輸入與相同 as_of 可完整重現。</p>"
        "<p>本文僅描述市場資料所呈現的狀態，不對任何交易或決策提供指引。</p></footer>"
    )

    from .lint import assert_no_advice

    return assert_no_advice(_document(f"{bundle.asset} 價格資料分析", body))
